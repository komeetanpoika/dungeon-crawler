// Shared plumbing for the concept-sheet extractors (extract-serpent-sheet.mjs,
// extract-wraith-sheet.mjs): premultiplied box downsampling and laying the
// finished frames onto a uniform-cell sheet plus its generated metadata
// module. Each extractor owns the part that differs per sheet — finding the
// frames and keying the backdrop — and hands over RGBA frames.
import * as fs from 'node:fs'
import * as path from 'node:path'
import { writePng } from './png-write.mjs'

// Box downsample an RGBA frame by an integer factor, averaging colour with
// alpha weights so transparent neighbours never darken an edge.
export function downsample({ w, h, rgba }, scale) {
  const W = Math.ceil(w / scale), H = Math.ceil(h / scale)
  const out = new Uint8Array(W * H * 4)
  for (let Y = 0; Y < H; Y++) for (let X = 0; X < W; X++) {
    let r = 0, g = 0, b = 0, a = 0, n = 0
    for (let dy = 0; dy < scale; dy++) for (let dx = 0; dx < scale; dx++) {
      const x = X * scale + dx, y = Y * scale + dy
      if (x >= w || y >= h) continue
      const i = (y * w + x) * 4, al = rgba[i + 3] / 255
      r += rgba[i] * al; g += rgba[i + 1] * al; b += rgba[i + 2] * al; a += al; n++
    }
    const o = (Y * W + X) * 4
    if (a > 0) { out[o] = Math.round(r / a); out[o + 1] = Math.round(g / a); out[o + 2] = Math.round(b / a) }
    out[o + 3] = Math.round(255 * a / n)
  }
  return { w: W, h: H, rgba: out }
}

// rows: [{ name, frames: [{ w, h, rgba }] }]. Every frame is centred in a
// cell as wide as the widest frame; `align` picks 'bottom' (a waterline that
// must stay put) or 'top' (a head that must stay put) inside a cell as tall
// as the tallest. Writes the PNG and a `SHEET` metadata module describing
// the grid, and returns the metadata.
export function writeSheet({ outPng, outMeta, rows, align = 'bottom', source, note = '' }) {
  const cellW = Math.max(...rows.flatMap(r => r.frames.map(f => f.w)))
  const cellH = Math.max(...rows.flatMap(r => r.frames.map(f => f.h)))
  const cols = Math.max(...rows.map(r => r.frames.length))
  const sheetW = cellW * cols, sheetH = cellH * rows.length
  const sheet = new Uint8Array(sheetW * sheetH * 4)
  rows.forEach((row, ri) => row.frames.forEach((f, ci) => {
    const ox = ci * cellW + Math.floor((cellW - f.w) / 2)
    const oy = ri * cellH + (align === 'top' ? 0 : cellH - f.h)
    for (let y = 0; y < f.h; y++) sheet.set(f.rgba.subarray(y * f.w * 4, (y + 1) * f.w * 4), ((oy + y) * sheetW + ox) * 4)
  }))
  fs.mkdirSync(path.dirname(outPng), { recursive: true })
  writePng(outPng, sheetW, sheetH, sheet)
  const meta = { cellW, cellH, rows: Object.fromEntries(rows.map((r, i) => [r.name, { row: i, frames: r.frames.length }])) }
  fs.writeFileSync(outMeta,
    `// Generated by ${source} — do not edit.\n` +
    `// Cells are ${cellW}x${cellH} px; frames sit centred and ${align}-aligned in their cell\n` +
    `// (row order: ${rows.map(r => r.name).join(', ')}).${note ? ' ' + note : ''}\n` +
    `export const SHEET = ${JSON.stringify(meta, null, 2)}\n`)
  return { meta, sheetW, sheetH }
}
