// Nearest walkable, prop-free cell to (x, y) by expanding square search.
function nearestOpen(m, x, y) {
  for (let r = 0; r < Math.max(m.w, m.h); r++) {
    for (let dy = -r; dy <= r; dy++) for (let dx = -r; dx <= r; dx++) {
      if (Math.max(Math.abs(dx), Math.abs(dy)) !== r) continue
      const nx = x + dx, ny = y + dy
      if (nx < 1 || ny < 1 || nx >= m.w - 1 || ny >= m.h - 1) continue
      if (m.walk[ny][nx] === '1' && m.prop[ny][nx] < 0) return { x: nx, y: ny }
    }
  }
  throw new Error(`no open cell near ${x},${y}`)
}

const maps = {}
for (const e of EXPORTS) {
  const m = JSON.parse(fs.readFileSync(path.join(HERE, 'out/maps', e.file), 'utf8'))
  const dungeons = m.pois.filter(p => p.kind === 'dungeon_entrance')
  if (dungeons.length !== e.caveDepths.length)
    throw new Error(`${m.name}: ${dungeons.length} dungeon entrances but ${e.caveDepths.length} caveDepths`)
  let exit = null
  if (e.exitPoi) {
    const poi = m.pois.find(p => p.label === e.exitPoi)
    if (!poi) throw new Error(`${m.name}: no POI labeled '${e.exitPoi}'`)
    exit = nearestOpen(m, poi.x, poi.y)
  }
  maps[e.depth] = {
    name: m.name, title: e.title, w: m.w, h: m.h,
    palette: m.palette, ground: m.ground, prop: m.prop, walk: m.walk,
    pois: m.pois, playerSpawn: m.playerSpawn, caveDepths: e.caveDepths, exit,
    npcs: e.npcs ?? null, starter: e.starter ?? null,
    leap: e.leap ?? undefined,
  }
}

const body = `// Generated by tools/static-overworld/export-game-maps.mjs — do not edit.
// Static open maps, keyed by the depth (Adventure order, cheat level<N>).
export const OPEN_MAPS = ${JSON.stringify(maps)}

// Every sprite name any open map references, for the loadSprites call.
export const OPEN_MAP_SPRITES = [...new Set(Object.values(OPEN_MAPS).flatMap(m => m.palette))]
`
fs.writeFileSync(OUT, body)
