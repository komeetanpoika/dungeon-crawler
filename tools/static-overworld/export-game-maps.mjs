// Export static overworld maps into the game as a JS module.
// Usage: node export-game-maps.mjs   -> ../../renderer/data/open-maps.js
//
// Only the maps listed in EXPORTS ship; the rest of out/maps stays
// tool-side. Depth is the LEVEL_CONFIG slot the map occupies.
import * as fs from 'node:fs'
import * as path from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const OUT = path.resolve(HERE, '../../renderer/data/open-maps.js')

const EXPORTS = [
  { depth: 7, file: 'forest-1-clearings.json', title: 'Clearings' },
]

const maps = {}
for (const e of EXPORTS) {
  const m = JSON.parse(fs.readFileSync(path.join(HERE, 'out/maps', e.file), 'utf8'))
  maps[e.depth] = {
    name: m.name, title: e.title, w: m.w, h: m.h,
    palette: m.palette, ground: m.ground, prop: m.prop, walk: m.walk,
    pois: m.pois, playerSpawn: m.playerSpawn,
  }
}

const body = `// Generated by tools/static-overworld/export-game-maps.mjs — do not edit.
// Static open maps, keyed by the depth (cheat code level<N>) that loads them.
export const OPEN_MAPS = ${JSON.stringify(maps)}

// Every sprite name any open map references, for the loadSprites call.
export const OPEN_MAP_SPRITES = [...new Set(Object.values(OPEN_MAPS).flatMap(m => m.palette))]
`
fs.writeFileSync(OUT, body)
console.log('wrote', OUT, (fs.statSync(OUT).size / 1024).toFixed(0) + 'KB,', Object.keys(maps).length, 'map(s)')
