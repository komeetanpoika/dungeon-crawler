// node tools/make-jackal-sheet.mjs
// The jackal's frame sheet, from the wolf's: the same cells and poses
// (renderer/assets/npcs/wolf.png, built by extract-wolf-sheet.mjs), the grey
// coat turned to a jackal's: sand flanks, a dark grizzled saddle along the
// back, pale belly and legs. Writes renderer/assets/npcs/jackal.png and
// jackal-sheet.js (the wolf's grid under the jackal's name).
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { readPng } from './png-read.mjs'
import { writePng } from './png-write.mjs'
import { SHEET } from '../renderer/assets/npcs/wolf-sheet.js'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const src = readPng(path.join(root, 'renderer/assets/npcs/wolf.png'))
const { width: W, height: H, pixels: px } = src
const out = new Uint8Array(px.length)

// luminance -> colour along a ramp of [luminance, r, g, b] stops
const ramp = stops => l => {
  let i = 0
  while (i < stops.length - 2 && stops[i + 1][0] <= l) i++
  const [l0, ...a] = stops[i], [l1, ...b] = stops[i + 1]
  const f = Math.max(0, Math.min(1, (l - l0) / (l1 - l0)))
  return a.map((v, k) => Math.round(v + (b[k] - v) * f))
}
const FLANK = ramp([[0, 38, 24, 12], [60, 112, 78, 40], [120, 190, 146, 86], [190, 232, 204, 150], [255, 250, 238, 208]])
const SADDLE = ramp([[0, 26, 20, 16], [60, 64, 52, 42], [120, 112, 96, 78], [190, 168, 150, 122], [255, 220, 206, 180]])
const BELLY = ramp([[0, 52, 36, 20], [60, 150, 112, 66], [120, 222, 190, 136], [190, 244, 226, 184], [255, 255, 248, 228]])

const { cellW, cellH, rows } = SHEET
for (const { row, frames } of Object.values(rows)) for (let f = 0; f < frames; f++) {
  const x0 = f * cellW, y0 = row * cellH
  // the animal's own top and bottom in this cell
  let top = cellH, bottom = 0
  for (let y = 0; y < cellH; y++) for (let x = 0; x < cellW; x++) if (px[((y0 + y) * W + x0 + x) * 4 + 3] > 40) { top = Math.min(top, y); bottom = Math.max(bottom, y) }
  const span = Math.max(1, bottom - top)
  for (let y = 0; y < cellH; y++) for (let x = 0; x < cellW; x++) {
    const o = ((y0 + y) * W + x0 + x) * 4
    if (y0 + y >= H || x0 + x >= W) continue
    const a = px[o + 3]
    if (!a) continue
    const l = 0.299 * px[o] + 0.587 * px[o + 1] + 0.114 * px[o + 2]
    const v = (y - top) / span                       // 0 at the ears, 1 at the paws
    // the saddle lies along the back; a ragged lower edge, so it does not read as a stripe
    const edge = 0.36 + 0.06 * Math.sin(x * 0.9 + f)
    const rgb = v < edge ? SADDLE(l) : v > 0.62 ? BELLY(l) : FLANK(l)
    out.set([...rgb, a], o)
  }
}
writePng(path.join(root, 'renderer/assets/npcs/jackal.png'), W, H, out)
fs.writeFileSync(path.join(root, 'renderer/assets/npcs/jackal-sheet.js'),
  `// Generated by tools/make-jackal-sheet.mjs — do not edit. The jackal's sheet is\n// the wolf's recoloured: the same cells and rows.\nexport { SHEET } from './wolf-sheet.js'\n`)
console.log('jackal.png', W, 'x', H)
