import test from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { pathToFileURL } from 'node:url'
import { writePng } from '../tools/png-write.mjs'
import { encodeMask } from '../tools/monster-cutter/mask.js'
import { buildCut, checkCut } from '../tools/monster-cutter/build-cut.js'
import { installCut, cutStatus } from '../tools/monster-cutter/install-cut.js'
import { CUTOUT_MARKER, rigModuleSource } from '../tools/monster-cutter/templates.js'

const W = 100, H = 100
const ROOT = path.resolve(import.meta.dirname, '..')

// A temp project root holding a torso-and-arm figure and its cut file.
function makeRoot({ short = false } = {}) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'cutter-build-'))
  for (const d of ['assets/cuts', 'renderer/assets/monsters', 'renderer/render/monster-rigs', 'renderer/data/monsters'])
    fs.mkdirSync(path.join(root, d), { recursive: true })
  fs.writeFileSync(path.join(root, 'renderer/data/monsters/index.json'), '[]')
  const mask = new Uint8Array(W * H), rgba = new Uint8Array(W * H * 4)
  for (let i = 0; i < W * H; i++) rgba.set([255, 255, 255, 255], i * 4)
  const rect = (x, y, w, h, col) => { for (let j = y; j < y + h; j++) for (let i = x; i < x + w; i++) { mask[j * W + i] = 1; rgba.set([...col, 255], (j * W + i) * 4) } }
  rect(30, 20, 40, 60, [255, 0, 0]); rect(20, 25, 10, 40, [0, 0, 255])
  writePng(path.join(root, 'assets/cuts/t.png'), W, H, rgba)
  const pieces = [
    { id: 'torso', role: 'torso', side: null, parent: null, seed: [50, 50], cut: null, pivot: [50, 50], z: 0, claims: [] },
    { id: 'arm', role: 'arm', side: 'left', parent: 'torso', seed: [22, 40],
      cut: short ? [[30, 40], [30, 45]] : [[30, 22], [30, 68]], pivot: [29, 40], z: 1, claims: [] },
  ]
  const cut = { version: 1, name: 't', source: 'assets/cuts/t.png', credit: null, w: W, h: H, mask: encodeMask(mask),
    view: 'front', faces: 'left', outHeight: 30, outline: '#102030', pieces, points: { chest: { piece: 'torso', x: 50, y: 40 } } }
  fs.writeFileSync(path.join(root, 'assets/cuts/t.json'), JSON.stringify(cut))
  return { root, cut }
}
const rigPath = root => path.join(root, 'renderer/render/monster-rigs/t.js')
const defPath = root => path.join(root, 'renderer/data/monsters/t.json')
const readDef = root => JSON.parse(fs.readFileSync(defPath(root), 'utf8'))

test('buildCut writes an atlas and a PARTS module that imports and matches', async () => {
  const { root, cut } = makeRoot()
  const { atlasPath, partsPath } = buildCut({ root, name: 't' })
  assert.ok(fs.existsSync(atlasPath))
  const text = fs.readFileSync(partsPath, 'utf8')
  assert.ok(text.startsWith('// Generated by tools/monster-cutter from assets/cuts/t.json — do not edit.'))
  const { PARTS } = await import(pathToFileURL(partsPath).href)
  assert.equal(PARTS.pieces.length, cut.pieces.length)
})

test('buildCut names leaking pieces', () => {
  const { root } = makeRoot({ short: true })
  assert.throws(() => buildCut({ root, name: 't' }), /leaks: arm/)
})

test('installCut writes the rig module from the template and creates the def', () => {
  const { root } = makeRoot()
  const r = installCut({ root, name: 't' })
  assert.deepEqual(r, { createdRig: true, createdDef: true, switched: false })
  assert.equal(fs.readFileSync(rigPath(root), 'utf8').split('\n')[0], CUTOUT_MARKER)
  assert.equal(fs.readFileSync(rigPath(root), 'utf8'), rigModuleSource('t'))
  assert.deepEqual(readDef(root), { rig: 't', params: {}, stats: { hp: 10, dmg: 1, speed: 60 }, behavior: {}, hooks: false, spawn: null, tuning: {}, name: 't' })
  assert.deepEqual(JSON.parse(fs.readFileSync(path.join(root, 'renderer/data/monsters/index.json'), 'utf8')), ['t'])
  assert.deepEqual(cutStatus({ root, name: 't' }), { reserved: false, def: { exists: true, rig: 't' }, rig: { exists: true, cutout: true } })
})

test('the generated rig module imports the engine and the parts, and runs', async () => {
  const { root } = makeRoot()
  buildCut({ root, name: 't' })
  installCut({ root, name: 't' })
  for (const f of ['cutout.js', 'anims.js', 'pixel.js']) fs.copyFileSync(path.join(ROOT, 'renderer/render/monster-rigs', f), path.join(root, 'renderer/render/monster-rigs', f))
  const rig = await import(pathToFileURL(rigPath(root)).href)
  for (const k of ['RIG_ID', 'PARAM_SCHEMA', 'drawMonster', 'hitHalf', 'hitShape', 'drawnTop', 'anchor', '_setSheetImage']) assert.ok(k in rig, k)
  assert.equal(rig.RIG_ID, 't')
})

test('installCut refuses to overwrite a hand-written rig', () => {
  const { root } = makeRoot()
  fs.writeFileSync(rigPath(root), 'export const x = 1\n')
  assert.throws(() => installCut({ root, name: 't' }), /not a cut-out rig/)
  assert.equal(fs.readFileSync(rigPath(root), 'utf8'), 'export const x = 1\n')
})

test('checkCut refuses an empty mask', () => {
  const { root } = makeRoot()
  const cut = JSON.parse(fs.readFileSync(path.join(root, 'assets/cuts/t.json'), 'utf8'))
  cut.mask = encodeMask(new Uint8Array(W * H))
  assert.throws(() => checkCut(cut, 't'), e => e.status === 400 && /mask is empty/.test(e.message))
})

test('index is not a valid cut name', () => {
  const { root } = makeRoot()
  assert.throws(() => installCut({ root, name: 'index' }), e => e.status === 400 && /index/.test(e.message))
  assert.throws(() => buildCut({ root, name: 'index' }), e => e.status === 400 && /index/.test(e.message))
})

test('installCut accepts a rig whose first line starts with the cutout-rig prefix, and leaves it alone', () => {
  const { root } = makeRoot()
  const src = '// cutout-rig: hand-written over the shared engine\nexport const x = 1\n'
  fs.writeFileSync(rigPath(root), src)
  assert.equal(cutStatus({ root, name: 't' }).rig.cutout, true)
  installCut({ root, name: 't' })
  assert.equal(fs.readFileSync(rigPath(root), 'utf8'), src)
})

test('installCut asks before switching a def on another rig, then switches keeping the rest', () => {
  const { root } = makeRoot()
  const def = { rig: 'quadruped', params: { size: 3 }, stats: { hp: 99, dmg: 5, speed: 10 }, behavior: { weapon: 'x' }, hooks: true, spawn: null, tuning: { a: 1 }, name: 't' }
  fs.writeFileSync(defPath(root), JSON.stringify(def))
  assert.throws(() => installCut({ root, name: 't' }), e => e.needsSwitch === true && /def uses rig quadruped/.test(e.message))
  assert.equal(readDef(root).rig, 'quadruped')
  const r = installCut({ root, name: 't', switchRig: true })
  assert.equal(r.switched, true)
  assert.deepEqual(readDef(root), { ...def, rig: 't', params: {} })
})

test('re-installing over a def already on its cut rig leaves params, stats and tuning untouched', () => {
  const { root } = makeRoot()
  installCut({ root, name: 't' })
  const def = { ...readDef(root), params: { size: 4 }, stats: { hp: 77, dmg: 3, speed: 40 }, tuning: { k: 2 } }
  fs.writeFileSync(defPath(root), JSON.stringify(def))
  const r = installCut({ root, name: 't' })
  assert.deepEqual(r, { createdRig: false, createdDef: false, switched: false })
  assert.deepEqual(readDef(root), def)
})

test('installCut refuses reserved and invalid names', () => {
  const { root } = makeRoot()
  assert.throws(() => installCut({ root, name: 'dragon' }), /reserved/)
  assert.throws(() => installCut({ root, name: 'Bad Name' }), /invalid/)
  assert.equal(cutStatus({ root, name: 'dragon' }).reserved, true)
})

test('buildCut and cutStatus refuse a name that is not a plain monster name', () => {
  const { root } = makeRoot()
  assert.throws(() => buildCut({ root, name: '../x' }), /invalid monster name/)
  assert.throws(() => cutStatus({ root, name: '../x' }), /invalid monster name/)
})

test('buildCut leaves no temp files beside the parts', () => {
  const { root } = makeRoot()
  buildCut({ root, name: 't' })
  assert.deepEqual(fs.readdirSync(path.join(root, 'renderer/assets/monsters')).sort(), ['t-parts.js', 't-parts.png'])
})

test('a def file that does not parse is an error, never overwritten', () => {
  const { root } = makeRoot()
  fs.writeFileSync(defPath(root), '{broken')
  assert.throws(() => installCut({ root, name: 't' }), /def t\.json is not valid JSON/)
  assert.equal(fs.readFileSync(defPath(root), 'utf8'), '{broken')
})
